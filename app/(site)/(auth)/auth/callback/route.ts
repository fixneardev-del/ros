import { NextResponse } from "next/server";
import type { EmailOtpType } from "@supabase/supabase-js";
import { isSupabaseConfigured } from "@/lib/env";
import { getAccountState } from "@/lib/auth-admin";
import { landingPath, safeNextPath } from "@/lib/next-path";
import { createServerSupabase } from "@/lib/supabase/server";

// Only the types this app issues are accepted. Anything else is treated as a
// bad link rather than passed through to Supabase.
const OTP_TYPES = new Set<EmailOtpType>(["recovery", "signup"]);

function otpType(value: string | null): EmailOtpType | null {
  if (!value) return null;
  return OTP_TYPES.has(value as EmailOtpType) ? (value as EmailOtpType) : null;
}

function authRedirect(path: string, origin: string) {
  const response = NextResponse.redirect(new URL(path, origin));
  response.headers.set(
    "Cache-Control",
    "private, no-cache, no-store, max-age=0",
  );
  return response;
}

export async function GET(request: Request) {
  const url = new URL(request.url);
  const code = url.searchParams.get("code");
  const tokenHash = url.searchParams.get("token_hash");
  const type = otpType(url.searchParams.get("type"));
  const requestedNext = url.searchParams.get("next");
  const next = safeNextPath(requestedNext, "/account");

  if (isSupabaseConfigured()) {
    // Links generated by this app carry a hashed token instead of a PKCE
    // code, so the reset email can come from Resend rather than Supabase.
    if (tokenHash && type) {
      try {
        const supabase = await createServerSupabase();
        const { data, error } = await supabase.auth.verifyOtp({
          type,
          token_hash: tokenHash,
        });

        if (!error) {
          const recoveryEmail = data.user?.email;
          const destination =
            type === "recovery" && recoveryEmail
              ? `/reset-password?email=${encodeURIComponent(recoveryEmail)}`
              : next;
          return authRedirect(destination, url.origin);
        }
      } catch {
        // Fall through to the friendly login error.
      }
    }

    if (code) {
      try {
        const supabase = await createServerSupabase();
        const { data, error } = await supabase.auth.exchangeCodeForSession(code);

        if (!error) {
          const sessionEmail = data.user?.email;
          const account = await getAccountState(data.user.id);
          const destination =
            next.startsWith("/reset-password") && sessionEmail
              ? `/reset-password?email=${encodeURIComponent(sessionEmail)}`
              : landingPath({
                  ...account,
                  requested: requestedNext ?? undefined,
                });
          return authRedirect(destination, url.origin);
        }
      } catch {
        // Fall through to the friendly login error.
      }
    }
  }

  return authRedirect("/login?error=auth", url.origin);
}
